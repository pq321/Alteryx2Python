"""Standalone native-Python code generation for editor workflows.

Emits a self-contained pandas script from an editor graph document: no
alteryx2python imports, no runtime dependency - the Alteryx semantics of the
supported tool subset are translated into plain pandas operations.

Expression subset: field references use Alteryx '[Field]' syntax and are
rewritten to pandas column access ('df["Field"]'); '=' becomes '==';
AND/OR/NOT become Python operators. Anything outside the subset is reported
in 'unsupported' so the editor can warn instead of silently miscompiling.
"""
from __future__ import annotations

import re
from typing import Any

_FIELD_REF = re.compile(r"\[([A-Za-z0-9_ ]+)\]")
_ROW_PREV_REF = re.compile(r"\[Row-1:([A-Za-z0-9_ ]+)\]")


def translate_expression(expression: str, frame: str) -> str:
    """Translate an Alteryx-style expression into a pandas column-access expression."""
    result = _FIELD_REF.sub(lambda match: f'{frame}["{match.group(1)}"]', str(expression))
    result = re.sub(r"(?<![=!<>])=(?!=)", "==", result)
    result = re.sub(r"\bAND\b", "and", result, flags=re.IGNORECASE)
    result = re.sub(r"\bOR\b", "or", result, flags=re.IGNORECASE)
    result = re.sub(r"\bNOT\b", "not", result, flags=re.IGNORECASE)
    return result


def _var(node_id: str) -> str:
    return "df_" + re.sub(r"[^A-Za-z0-9_]", "_", str(node_id))


def generate_standalone(graph: dict[str, Any]) -> tuple[str, list[str]]:
    """Return (python_source, unsupported_notes) for an editor graph."""
    nodes = {str(node["id"]): node for node in graph.get("nodes", [])}
    edges = graph.get("edges", [])
    incoming: dict[str, list[dict[str, Any]]] = {}
    for edge in edges:
        incoming.setdefault(str(edge["to"]), []).append(edge)

    order = _topological_order(nodes, edges)
    lines = [
        '"""Generated by Alteryx2Python - standalone native pandas workflow."""',
        "import re",
        "import pandas as pd",
        "",
        "_PREV_RE = re.compile(" + repr(_ROW_PREV_REF.pattern) + ")",
        "_FIELD_RE = re.compile(" + repr(_FIELD_REF.pattern) + ")",
        "",
        "def _fmt(value):",
        '    """Format cells the way the native Alteryx CSV writer does."""',
        "    if value is None:",
        "        return \"\"",
        "    try:",
        "        if not isinstance(value, str) and pd.isna(value):",
        "            return \"\"",
        "    except (TypeError, ValueError):",
        "        pass",
        "    if isinstance(value, float) and value == int(value) and abs(value) < 1e15:",
        "        return str(int(value))",
        "    return str(value)",
        "",
    ]
    unsupported: list[str] = []

    for node_id in order:
        node = nodes[node_id]
        kind = node.get("type", "")
        config = node.get("config") or {}
        var = _var(node_id)
        sources = incoming.get(node_id, [])
        source_var = _var(str(sources[0]["from"])) if sources else None
        try:
            emitted = _emit_node(kind, config, var, source_var, sources, node_id)
        except NotImplementedError as exc:
            unsupported.append(f"node {node_id} ({kind}): {exc}")
            lines.append(f"# {var}: {kind} is not translatable standalone yet ({exc})")
            lines.append(f"{var} = {source_var or 'pd.DataFrame()'}")
            continue
        lines.extend(emitted)
        lines.append("")
    return "\n".join(lines) + "\n", unsupported


def _topological_order(nodes, edges):
    remaining = dict(nodes)
    ordered = []
    resolved = set()
    while remaining:
        progress = False
        for node_id in list(remaining):
            deps = {str(edge["from"]) for edge in edges if str(edge["to"]) == node_id}
            if deps <= resolved:
                ordered.append(node_id)
                resolved.add(node_id)
                del remaining[node_id]
                progress = True
        if not progress:
            raise ValueError("workflow graph contains a cycle")
    return ordered


def _typed_column(values: list[Any]) -> list[Any]:
    """Statically infer a column's cell types the way native TextInput does.

    All-integer columns (ignoring nulls) become ints, all-parseable-float
    columns become floats, anything else stays textual.
    """
    non_empty = [str(value) for value in values if value is not None and str(value) != ""]
    if not non_empty:
        return [None if value in (None, "") else str(value) for value in values]

    def _int(value: str) -> bool:
        try:
            int(value)
            return True
        except ValueError:
            return False

    def _float(value: str) -> bool:
        try:
            float(value)
            return True
        except ValueError:
            return False

    if all(_int(value) for value in non_empty):
        return [None if value in (None, "") else int(str(value)) for value in values]
    if all(_float(value) for value in non_empty):
        return [None if value in (None, "") else float(str(value)) for value in values]
    return [None if value in (None, "") else str(value) for value in values]


def _emit_node(kind, config, var, source_var, sources, node_id):
    if kind == "TextInput":
        fields = [str(field) for field in config.get("fields", [])]
        rows = [list(row) for row in config.get("rows", [])]
        columns = ", ".join(
            '"' + field + '": ' + repr(_typed_column([row[index] if index < len(row) else None for row in rows]))
            for index, field in enumerate(fields)
        )
        return [var + " = pd.DataFrame({" + columns + "})"]

    if kind == "Formula":
        out = [var + " = " + source_var + ".copy()"]
        for item in config.get("expressions", []):
            field = str(item.get("field", ""))
            expression = translate_expression(str(item.get("expression", "")), source_var)
            out.append(var + '["' + field + '"] = ' + expression)
        return out

    if kind == "Filter":
        expression = translate_expression(str(config.get("expression", "")), source_var)
        mask = "_mask_" + var
        return [
            mask + " = " + expression,
            var + " = " + source_var + "[" + mask + "].copy().reset_index(drop=True)",
        ]

    if kind == "Select":
        keep = [
            str(item.get("field", ""))
            for item in config.get("fields", [])
            if str(item.get("selected", "True")).lower() == "true"
        ]
        if not keep:
            raise NotImplementedError("Select needs at least one selected field")
        columns = ", ".join('"' + column + '"' for column in keep)
        return [var + " = " + source_var + "[[" + columns + "]].copy()"]

    if kind == "Sort":
        fields = [str(item.get("field", "")) for item in config.get("order", [])]
        ascending = [str(item.get("order", "Ascending")).lower() == "ascending" for item in config.get("order", [])]
        if not fields:
            raise NotImplementedError("Sort needs at least one field")
        columns = ", ".join('"' + column + '"' for column in fields)
        asc = ", ".join(str(value) for value in ascending)
        return [
            var + " = " + source_var + ".sort_values([" + columns + "], ascending=[" + asc + "]).reset_index(drop=True)"
        ]

    if kind == "Summarize":
        group_fields = [str(item.get("field", "")) for item in config.get("actions", []) if item.get("action") == "GroupBy"]
        named = []
        for item in config.get("actions", []):
            action = str(item.get("action", ""))
            field = str(item.get("field", ""))
            rename = str(item.get("rename", "")) or (action + "_" + field)
            if action == "GroupBy":
                continue
            if action == "Count":
                named.append('"' + rename + '": ("' + field + '", "size")')
                continue
            pandas_op = {"Sum": "sum", "Avg": "mean", "Min": "min", "Max": "max"}.get(action)
            if pandas_op is None:
                raise NotImplementedError("Summarize action " + action + " is not mapped")
            named.append('"' + rename + '": ("' + field + '", "' + pandas_op + '")')
        if not group_fields:
            raise NotImplementedError("Summarize needs at least one GroupBy field")
        group_list = ", ".join('"' + field + '"' for field in group_fields)
        return [
            var + " = " + source_var + ".groupby([" + group_list + "], dropna=False).agg(**{",
            "    " + ",\n    ".join(named),
            "}).reset_index()",
        ]

    if kind == "Join":
        left = sources[0]
        right = next(
            (edge for edge in sources if edge.get("toAnchor") == "Right"),
            sources[1] if len(sources) > 1 else None,
        )
        if right is None:
            raise NotImplementedError("Join needs Left and Right inputs")
        left_var = _var(str(left["from"]))
        right_var = _var(str(right["from"]))
        key = str(config.get("leftField", ""))
        key_right = str(config.get("rightField", key))
        return [
            var + " = pd.merge(",
            "    " + left_var + ",",
            "    " + right_var + ",",
            '    left_on="' + key + '", right_on="' + key_right + '", how="inner",',
            '    suffixes=("", "_right"))',
        ]

    if kind == "Union":
        inputs = ",\n    ".join(_var(str(edge["from"])) for edge in sources)
        return [var + " = pd.concat([", "    " + inputs + ",", "]).reset_index(drop=True)"]

    if kind == "RecordID":
        field = str(config.get("fieldName", "RecordID"))
        return [
            var + " = " + source_var + ".copy()",
            var + '["' + field + '"] = range(1, len(' + source_var + ") + 1)",
        ]

    if kind == "Sample":
        mode = str(config.get("mode", "First"))
        n = int(str(config.get("n", "10")))
        if mode == "First":
            return [var + " = " + source_var + ".head(" + str(n) + ").copy()"]
        if mode == "Last":
            return [var + " = " + source_var + ".tail(" + str(n) + ").copy()"]
        raise NotImplementedError("Sample mode " + mode + " is not mapped")

    if kind == "Unique":
        field = str(config.get("field", ""))
        return [
            var + " = " + source_var + '.drop_duplicates(subset=["' + field + '"], keep="first").reset_index(drop=True)'
        ]

    if kind == "CrossTab":
        group = str(config.get("groupBy", ""))
        header = str(config.get("header", ""))
        data_field = str(config.get("dataField", ""))
        method = str(config.get("method", "First"))
        agg = {"Sum": "sum", "First": "first", "Avg": "mean", "Min": "min", "Max": "max"}.get(method)
        if agg is None:
            raise NotImplementedError("CrossTab method " + method + " is not mapped")
        return [
            var + ' = ' + source_var + '.pivot_table(index="' + group + '", columns="' + header + '",',
            '    values="' + data_field + '", aggfunc="' + agg + '").reset_index()',
            var + ".columns.name = None",
        ]

    if kind == "Transpose":
        keys = [str(field) for field in config.get("keyFields", [])]
        data = [str(field) for field in config.get("dataFields", [])]
        key_list = ", ".join('"' + field + '"' for field in keys)
        value_vars = ", ".join('"' + field + '"' for field in data)
        return [
            var + " = " + source_var + ".melt(id_vars=[" + key_list + "], value_vars=[" + value_vars + "],",
            '    var_name="Name", value_name="Value")',
        ]

    if kind == "RegEx":
        field = str(config.get("field", ""))
        pattern = str(config.get("pattern", ""))
        output_field = str(config.get("outputField", "Parsed"))
        extract = "_extract_" + var
        return [
            var + " = " + source_var + ".copy()",
            extract + ' = ' + source_var + '["' + field + '"].astype(str).str.extract(r"' + _quoted(pattern) + '")',
            var + '["' + output_field + '"] = ' + extract + "[0]",
        ]

    if kind == "DateTime":
        input_field = str(config.get("inputField", ""))
        output_field = str(config.get("outputField", ""))
        date_format = (
            str(config.get("format", "yyyy-MM-dd"))
            .replace("yyyy", "%Y")
            .replace("MM", "%m")
            .replace("dd", "%d")
        )
        return [
            var + " = " + source_var + ".copy()",
            var + '["' + output_field + '"] = pd.to_datetime(' + source_var + '["' + input_field + '"], format="' + date_format + '")',
        ]

    if kind == "MultiRowFormula":
        expression = str(config.get("expression", ""))
        field_name = str(config.get("fieldName", "NewField"))
        prev = "_prev_" + var
        return [
            var + " = " + source_var + ".copy()",
            var + '["' + field_name + '"] = None',
            prev + " = " + source_var + ".shift(1)",
            "for _i in " + var + ".index:",
            "    _ctx = {**" + source_var + ".loc[_i].to_dict()}",
            "    _expr = " + repr(expression),
            "    for _m in _PREV_RE.findall(_expr):",
            '        _ctx["__prev_" + _m] = ' + prev + '.loc[_i, _m]',
            '        _expr = _expr.replace("[Row-1:" + _m + "]", "__prev_" + _m)',
            "    for _m in _FIELD_RE.findall(_expr):",
            '        _expr = _expr.replace("[" + _m + "]", "_ctx[" + repr(_m) + "]")',
            "    try:",
            var + '.loc[_i, "' + field_name + '"] = eval(_expr)',
            "    except TypeError:",
            var + '.loc[_i, "' + field_name + '"] = None',
        ]

    if kind == "RunningTotal":
        field = str(config.get("field", ""))
        return [
            var + " = " + source_var + ".copy()",
            var + '["Total_' + field + '"] = ' + source_var + '["' + field + '"].cumsum()',
        ]

    if kind == "Rank":
        field = str(config.get("field", ""))
        order = str(config.get("order", "Descending"))
        ascending = "True" if order.lower() == "ascending" else "False"
        return [
            var + " = " + source_var + ".copy()",
            var + '["Rank_' + field + '"] = ' + source_var + '["' + field + '"].rank(ascending=' + ascending + ', method="min").astype("Int64")',
        ]

    if kind == "TextToColumns":
        field = str(config.get("field", ""))
        delimiter = str(config.get("delimiter", ","))
        split = "_split_" + var
        return [
            var + " = " + source_var + ".copy()",
            split + ' = ' + source_var + '["' + field + '"].astype(str).str.split("' + delimiter + '", expand=True)',
            var + " = pd.concat([" + var + ", " + split + "], axis=1)",
        ]

    if kind == "DbFileOutput":
        file_name = str(config.get("file", "output.csv"))
        return [
            var + " = " + source_var,
            var + " = " + source_var + ".map(_fmt)",
            var + '.to_csv(r"' + file_name + '", index=False)',
        ]

    raise NotImplementedError("tool " + kind + " has no standalone translation")


def _quoted(value: str) -> str:
    return str(value).replace("\\", "\\\\").replace('"', '\\"')
