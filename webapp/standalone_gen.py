"""Standalone native-Python code generation for editor workflows.

Emits a self-contained pandas script from an editor graph document: no
alteryx2python imports, no runtime dependency - the Alteryx semantics of the
supported tool subset are translated into plain pandas operations.

Expression subset: field references use Alteryx '[Field]' syntax and are
rewritten to pandas column access ('df["Field"]'); '=' becomes '==';
AND/OR/NOT become Python operators. Anything outside the subset is reported
in 'unsupported' so the editor can warn instead of silently miscompiling.
"""
from __future__ import annotations

import re
import json
import ast
from typing import Any

_FIELD_REF = re.compile(r"\[([^\[\]:]+)\]")
_ROW_PREV_REF = re.compile(r"\[Row-1:([^\[\]:]+)\]")


def translate_expression(expression: str, frame: str) -> str:
    """Translate an Alteryx-style expression into a pandas column-access expression."""
    result = _FIELD_REF.sub(lambda match: f'{frame}[{json.dumps(match.group(1), ensure_ascii=False)}]', str(expression))
    result = re.sub(r"(?<![=!<>])=(?!=)", "==", result)
    result = re.sub(r"\bAND\b", "and", result, flags=re.IGNORECASE)
    result = re.sub(r"\bOR\b", "or", result, flags=re.IGNORECASE)
    result = re.sub(r"\bNOT\b", "not", result, flags=re.IGNORECASE)
    return result


def _var(node_id: str) -> str:
    return "df_" + re.sub(r"[^A-Za-z0-9_]", "_", str(node_id))


def generate_standalone(graph: dict[str, Any]) -> tuple[str, list[str]]:
    """Return (python_source, unsupported_notes) for an editor graph."""
    nodes = {str(node["id"]): node for node in graph.get("nodes", [])}
    edges = graph.get("edges", [])
    incoming: dict[str, list[dict[str, Any]]] = {}
    for edge in edges:
        incoming.setdefault(str(edge["to"]), []).append(edge)

    order = _topological_order(nodes, edges)
    lines = [
        '"""Generated by Alteryx2Python - standalone native pandas workflow."""',
        "import re",
        "import pandas as pd",
        "from pathlib import Path",
        "",
        "_PREV_RE = re.compile(" + repr(_ROW_PREV_REF.pattern) + ")",
        "_FIELD_RE = re.compile(" + repr(_FIELD_REF.pattern) + ")",
        "",
        "def _fmt(value):",
        '    """Format cells the way the native Alteryx CSV writer does."""',
        "    if value is None:",
        "        return \"\"",
        "    try:",
        "        if not isinstance(value, str) and pd.isna(value):",
        "            return \"\"",
        "    except (TypeError, ValueError):",
        "        pass",
        "    if isinstance(value, float) and value == int(value) and abs(value) < 1e15:",
        "        return str(int(value))",
        "    return str(value)",
        "",
    ]
    unsupported: list[str] = []

    for node_id in order:
        node = nodes[node_id]
        kind = node.get("type", "")
        config = node.get("config") or {}
        var = _var(node_id)
        sources = [{**edge, "sourceVar": _source_var(edge, nodes)} for edge in incoming.get(node_id, [])]
        source_var = sources[0]["sourceVar"] if sources else None
        try:
            emitted = _emit_node(kind, config, var, source_var, sources, node_id)
        except NotImplementedError as exc:
            unsupported.append(f"node {node_id} ({kind}): {exc}")
            lines.append(f"# {var}: {kind} is not translatable standalone yet ({exc})")
            lines.append(f"{var} = {source_var or 'pd.DataFrame()'}")
            continue
        lines.extend(emitted)
        lines.append("")
    source = "\n".join(lines) + "\n"
    try:
        ast.parse(source)
    except SyntaxError as exc:
        unsupported.append(f"Generated Python syntax: {exc.msg} (line {exc.lineno})")
    return source, unsupported


def _source_var(edge, nodes):
    source = str(edge["from"])
    kind = nodes[source]["type"]
    anchor = edge.get("fromAnchor", "Output")
    suffix = {("Filter", "False"): "_false", ("Unique", "Duplicates"): "_duplicates",
              ("Join", "Left"): "_left", ("Join", "Right"): "_right"}.get((kind, anchor), "")
    return _var(source) + suffix


def _topological_order(nodes, edges):
    remaining = dict(nodes)
    ordered = []
    resolved = set()
    while remaining:
        progress = False
        for node_id in list(remaining):
            deps = {str(edge["from"]) for edge in edges if str(edge["to"]) == node_id}
            if deps <= resolved:
                ordered.append(node_id)
                resolved.add(node_id)
                del remaining[node_id]
                progress = True
        if not progress:
            raise ValueError("workflow graph contains a cycle")
    return ordered


def _typed_column(values: list[Any]) -> list[Any]:
    """Statically infer a column's cell types the way native TextInput does.

    All-integer columns (ignoring nulls) become ints, all-parseable-float
    columns become floats, anything else stays textual.
    """
    non_empty = [str(value) for value in values if value is not None and str(value) != ""]
    if not non_empty:
        return [None if value in (None, "") else str(value) for value in values]

    def _int(value: str) -> bool:
        try:
            int(value)
            return True
        except ValueError:
            return False

    def _float(value: str) -> bool:
        try:
            float(value)
            return True
        except ValueError:
            return False

    if all(_int(value) for value in non_empty):
        return [None if value in (None, "") else int(str(value)) for value in values]
    if all(_float(value) for value in non_empty):
        return [None if value in (None, "") else float(str(value)) for value in values]
    return [None if value in (None, "") else str(value) for value in values]


def _emit_node(kind, config, var, source_var, sources, node_id):
    if kind == "TextInput":
        fields = [str(field) for field in config.get("fields", [])]
        rows = [list(row) for row in config.get("rows", [])]
        columns = ", ".join(
            repr(field) + ': ' + repr(_typed_column([row[index] if index < len(row) else None for row in rows]))
            for index, field in enumerate(fields)
        )
        return [var + " = pd.DataFrame({" + columns + "})"]

    if kind == "DbFileInput":
        return [var + " = pd.read_csv(" + repr(str(config.get("file", ""))) + ", encoding='utf-8')"]

    if kind == "Formula":
        out = [var + " = " + source_var + ".copy()"]
        for item in config.get("expressions", []):
            field = str(item.get("field", ""))
            expression = translate_expression(str(item.get("expression", "")), var)
            out.append(var + '[' + repr(field) + '] = pd.eval(' + repr(expression) + ', local_dict={' + repr(var) + ': ' + var + '}, engine="python")')
        return out

    if kind == "Filter":
        expression = translate_expression(str(config.get("expression", "")), source_var)
        mask = "_mask_" + var
        return [
            mask + " = pd.eval(" + repr(expression) + ", local_dict={" + repr(source_var) + ": " + source_var + '}, engine="python")',
            var + " = " + source_var + "[" + mask + "].copy().reset_index(drop=True)",
            var + "_false = " + source_var + "[~" + mask + "].copy().reset_index(drop=True)",
        ]

    if kind == "Select":
        keep = [
            str(item.get("field", ""))
            for item in config.get("fields", [])
            if str(item.get("selected", "True")).lower() == "true"
        ]
        if config.get("includeUnknown"):
            declared = [str(item.get("field", "")) for item in config.get("fields", [])]
            return [var + " = " + source_var + "[" + repr(keep) + " + [c for c in " + source_var + ".columns if c not in " + repr(declared) + "]].copy()"]
        if not keep:
            raise NotImplementedError("Select needs at least one selected field")
        columns = ", ".join(repr(column) for column in keep)
        return [var + " = " + source_var + "[[" + columns + "]].copy()"]

    if kind == "Sort":
        fields = [str(item.get("field", "")) for item in config.get("order", [])]
        ascending = [str(item.get("order", "Ascending")).lower() == "ascending" for item in config.get("order", [])]
        if not fields:
            raise NotImplementedError("Sort needs at least one field")
        columns = ", ".join(repr(column) for column in fields)
        asc = ", ".join(str(value) for value in ascending)
        return [
            var + " = " + source_var + ".sort_values([" + columns + "], ascending=[" + asc + "]).reset_index(drop=True)"
        ]

    if kind == "Summarize":
        actions = config.get("actions", [])
        grouped = [item for item in actions if item.get("action") == "GroupBy"]
        group_fields = [str(item.get("field", "")) for item in grouped]
        values = []
        for item in [*grouped, *[item for item in actions if item.get("action") != "GroupBy"]]:
            action = str(item.get("action", ""))
            field = str(item.get("field", ""))
            rename = str(item.get("rename", "")) or field
            series = "_group[" + repr(field) + "]"
            if action == "GroupBy":
                expression = series + ".iloc[0]"
            elif action == "Count":
                expression = "len(" + series + ")"
            elif action in {"Sum", "Avg"}:
                expression = "pd.to_numeric(" + series + ", errors='coerce')." + ("sum" if action == "Sum" else "mean") + "()"
            elif action in {"Min", "Max"}:
                expression = series + "." + action.lower() + "()"
            else:
                raise NotImplementedError("Summarize action " + action + " is not mapped")
            values.append(repr(rename) + ": " + expression)
        groups = source_var + ".groupby(" + repr(group_fields) + ", sort=False, dropna=False)" if group_fields else "[(None, " + source_var + ")]"
        return [
            "_rows_" + var + " = []",
            "for _, _group in " + groups + ":",
            "    _rows_" + var + ".append({" + ", ".join(values) + "})",
            var + " = pd.DataFrame(_rows_" + var + ")",
        ]

    if kind == "Join":
        left = next((edge for edge in sources if edge.get("toAnchor") == "Left"), sources[0])
        right = next(
            (edge for edge in sources if edge.get("toAnchor") == "Right"),
            sources[1] if len(sources) > 1 else None,
        )
        if right is None:
            raise NotImplementedError("Join needs Left and Right inputs")
        left_var = left["sourceVar"]
        right_var = right["sourceVar"]
        key = str(config.get("leftField", ""))
        key_right = str(config.get("rightField", key))
        return [
            var + " = pd.merge(",
            "    " + left_var + ".add_prefix('Left_'),",
            "    " + right_var + ".add_prefix('Right_'),",
            "    left_on=" + repr('Left_' + key) + ", right_on=" + repr('Right_' + key_right) + ", how='inner', sort=True,",
            '    suffixes=("", "_right"))',
            var + "_left = " + left_var + "[~" + left_var + "[" + repr(key) + "].isin(" + right_var + "[" + repr(key_right) + "])].copy().reset_index(drop=True)",
            var + "_right = " + right_var + "[~" + right_var + "[" + repr(key_right) + "].isin(" + left_var + "[" + repr(key) + "])].copy().reset_index(drop=True)",
        ]

    if kind == "Union":
        inputs = ",\n    ".join(edge["sourceVar"] for edge in sources)
        return [var + " = pd.concat([", "    " + inputs + ",", "]).reset_index(drop=True)"]

    if kind == "RecordID":
        field = str(config.get("fieldName", "RecordID"))
        return [
            var + " = " + source_var + ".copy()",
            var + ".insert(0, " + repr(field) + ", range(1, len(" + source_var + ") + 1))",
        ]

    if kind == "Sample":
        mode = str(config.get("mode", "First"))
        n = int(str(config.get("n", "10")))
        if mode == "First":
            return [var + " = " + source_var + ".head(" + str(n) + ").copy()"]
        if mode == "Last":
            return [var + " = " + source_var + ".tail(" + str(n) + ").copy()"]
        raise NotImplementedError("Sample mode " + mode + " is not mapped")

    if kind == "Unique":
        field = str(config.get("field", ""))
        return [
            var + " = " + source_var + '.drop_duplicates(subset=[' + repr(field) + '], keep="first").reset_index(drop=True)',
            var + "_duplicates = " + source_var + '[' + source_var + '.duplicated(subset=[' + repr(field) + '], keep="first")].copy().reset_index(drop=True)',
        ]

    if kind == "CrossTab":
        group = str(config.get("groupBy", ""))
        header = str(config.get("header", ""))
        data_field = str(config.get("dataField", ""))
        method = str(config.get("method", "First"))
        if method != "First":
            raise NotImplementedError("CrossTab method " + method + " is not mapped")
        groups = [group] if group else []
        return [
            "_rows_" + var + " = {}",
            "_headers_" + var + " = list(dict.fromkeys(" + source_var + "[" + repr(header) + "].dropna().astype(str)))",
            "for _row in " + source_var + ".to_dict('records'):",
            "    _key = tuple(_row[f] for f in " + repr(groups) + ")",
            "    _out = _rows_" + var + ".setdefault(_key, {f: _row[f] for f in " + repr(groups) + "})",
            "    if not pd.isna(_row[" + repr(header) + "]):",
            "        _out.setdefault(str(_row[" + repr(header) + "]), _row[" + repr(data_field) + "])",
            var + " = pd.DataFrame(list(_rows_" + var + ".values()), columns=" + repr(groups) + " + _headers_" + var + ")",
        ]

    if kind == "Transpose":
        keys = [str(field) for field in config.get("keyFields", [])]
        data = [str(field) for field in config.get("dataFields", [])]
        key_list = ", ".join(repr(field) for field in keys)
        value_vars = ", ".join(repr(field) for field in data)
        return [
            var + " = " + source_var + ".melt(id_vars=[" + key_list + "], value_vars=[" + value_vars + "],",
            '    var_name="Name", value_name="Value")',
        ]

    if kind == "RegEx":
        field = str(config.get("field", ""))
        pattern = str(config.get("pattern", ""))
        output_field = str(config.get("outputField", "Parsed"))
        extract = "_extract_" + var
        return [
            var + " = " + source_var + ".copy()",
            extract + ' = ' + source_var + '[' + repr(field) + '].fillna("").astype(str).str.extract(' + repr(pattern) + ')',
            var + '[' + repr(output_field) + '] = ' + extract + '[0].fillna("")',
        ]

    if kind == "DateTime":
        input_field = str(config.get("inputField", ""))
        output_field = str(config.get("outputField", ""))
        date_format = (
            str(config.get("format", "yyyy-MM-dd"))
            .replace("yyyy", "%Y")
            .replace("MM", "%m")
            .replace("dd", "%d")
        )
        return [
            var + " = " + source_var + ".copy()",
            var + '[' + repr(output_field) + '] = pd.to_datetime(' + source_var + '[' + repr(input_field) + '], errors="coerce").dt.strftime(' + repr(date_format) + ').fillna("")',
        ]

    if kind == "MultiRowFormula":
        expression = str(config.get("expression", ""))
        field_name = str(config.get("fieldName", "NewField"))
        return [
            var + " = " + source_var + ".copy()",
            var + '[' + repr(field_name) + '] = None',
            "for _i in " + var + ".index:",
            "    _ctx = {**" + var + ".loc[_i].to_dict()}",
            "    _expr = " + repr(expression),
            '    _expr = _FIELD_RE.sub(lambda _m: "_ctx[" + repr(_m.group(1)) + "]", _expr)',
            '    _prev = ' + var + '.loc[_i - 1].to_dict() if _i > 0 else {' + repr(field_name) + ': 0}',
            '    _expr = _PREV_RE.sub(lambda _m: "_prev.get(" + repr(_m.group(1)) + ")", _expr)',
            "    try:",
            '        ' + var + '.loc[_i, ' + repr(field_name) + '] = eval(_expr)',
            "    except TypeError:",
            '        ' + var + '.loc[_i, ' + repr(field_name) + '] = None',
        ]

    if kind == "RunningTotal":
        field = str(config.get("field", ""))
        return [
            var + " = " + source_var + ".copy()",
            var + '[' + repr('RunningTotal_' + field) + '] = pd.to_numeric(' + source_var + '[' + repr(field) + '], errors="coerce").fillna(0).cumsum()',
        ]

    if kind == "Rank":
        field = str(config.get("field", ""))
        order = str(config.get("order", "Descending"))
        ascending = "True" if order.lower() == "ascending" else "False"
        return [
            var + " = " + source_var + ".sort_values(" + repr(field) + ', ascending=' + ascending + ', kind="mergesort").reset_index(drop=True)',
            var + '["Rank"] = pd.to_numeric(' + var + '[' + repr(field) + '], errors="coerce").rank(ascending=' + ascending + ', method="first").astype("Int64")',
        ]

    if kind == "TextToColumns":
        from alteryx2python.tools.texttocolumns import _delimiter_pattern

        field = str(config.get("field", ""))
        delimiter = str(config.get("delimiter", ","))
        count = int(config.get("numFields", "3"))
        root = str(config.get("rootName") or field)
        split = "_split_" + var
        return [
            var + " = " + source_var + ".copy()",
            split + " = []",
            "for _value in " + source_var + '[' + repr(field) + ']:',
            '    _value = "" if pd.isna(_value) else str(_value)',
            '    _parts = re.split(' + repr(_delimiter_pattern(delimiter)) + ', _value)' if delimiter else '    _parts = [_value]',
            '    if len(_parts) > ' + str(count) + ':',
            '        _parts = _parts[:' + str(count - 1) + '] + [' + repr(delimiter[:1]) + '.join(_parts[' + str(count - 1) + ':])]',
            '    ' + split + '.append((_parts + [""] * ' + str(count) + ')[:' + str(count) + '])',
            'for _c in range(' + str(count) + '):',
            '    ' + var + '[' + repr(root) + ' + str(_c + 1)] = [_row[_c] for _row in ' + split + ']',
        ]

    if kind == "DbFileOutput":
        file_name = str(config.get("file", "output.csv"))
        return [
            var + " = " + source_var,
            var + " = " + source_var + ".map(_fmt)",
            "Path(" + repr(file_name) + ").parent.mkdir(parents=True, exist_ok=True)",
            var + '.to_csv(' + repr(file_name) + ', index=False, encoding="utf-8")',
        ]

    raise NotImplementedError("tool " + kind + " has no standalone translation")
