# Public official identifiers are shipped with the package, independently of an
# Alteryx installation. Mapping an identifier does not imply implementation.
CATALOG += tuple(CatalogEntry(**entry) for entry in json.loads(
    Path(__file__).with_name("official_catalog.json").read_text(encoding="utf-8")))

CATALOG_BY_PLUGIN: dict[str, CatalogEntry] = {entry.plugin_id: entry for entry in CATALOG}
TOOL_TYPES: frozenset[str] = frozenset(entry.tool_type for entry in CATALOG)


def catalog_entry_for_plugin(plugin_id: str) -> CatalogEntry | None:
    """Return the catalog entry for an exact GUI plugin id, if known."""
    return CATALOG_BY_PLUGIN.get(plugin_id)


def engine_binding_for_plugin(plugin_id: str) -> tuple[str | None, str | None, str | None]:
    """Return (engine_dll, engine_entry, engine_macro) observed for a plugin id."""
    entry = CATALOG_BY_PLUGIN.get(plugin_id)
    if entry is None:
        return None, None, None
    return entry.engine_dll, entry.engine_entry, entry.engine_macro

